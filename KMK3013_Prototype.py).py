# 1. PROCEDURAL TOOLS ARCHITECTURE
# ==========================================
class DyslexiaSupportTools:
    """Implements section 3.2: Procedural Knowledge (Tools)"""

    @staticmethod
    def text_chunking_tool(text: str) -> List[str]:
        """Divides long text blocks into smaller, bite-sized units."""
        # Split by sentences to create structured, manageable chunks
        sentences = re.split(r'(?<=[.!?]) +', text.strip())
        chunks = []
        current_chunk = []

        for sentence in sentences:
            current_chunk.append(sentence)
            if len(current_chunk) >= 2:  # Keep chunks safely short (1-2 sentences)
                chunks.append(" ".join(current_chunk))
                current_chunk = []
        if current_chunk:
            chunks.append(" ".join(current_chunk))
        return chunks

    @staticmethod
    def simplification_tool(text: str) -> str:
        """Decreases instruction and vocabulary complexity."""
        # Simple rule-based mapping simulating text simplification
        replacements = {
            "academic topics": "school work",
            "comprehending lengthy texts": "reading long books",
            "information retention": "remembering things",
            "cognitive overload": "brain feeling too full",
            "strategies": "steps"
        }
        simplified = text.lower()
        for complex_word, simple_word in replacements.items():
            simplified = simplified.replace(complex_word, simple_word)
        return simplified.capitalize()

    @staticmethod
    def phonics_support_tool(word: str) -> str:
        """Aids in word decoding using hyphenated sound-letter mapping."""
        # Simulated mapping for demonstrating decoding support
        phonics_db = {
            "dyslexia": "dys-lex-i-a (dis-lek-see-uh)",
            "reading": "read-ing (reed-ing)",
            "cognitive": "cog-ni-tive (kog-ni-tiv)",
            "comprehension": "com-pre-hen-sion (kom-pree-hen-shuhn)"
        }
        return phonics_db.get(word.lower(), f"{word.lower()} (Break it down into syllables slowly)")

    @staticmethod
    def sight_word_tool(word: str) -> str:
        """Highlights and recognizes common words to improve fluency."""
        return f"🌟 Look at this shape as a whole word: **{word.upper()}** 🌟"

    @staticmethod
    def motivation_tool() -> str:
        """Section 3.2: Offers positive reinforcement and emotional support."""
        return "✨ Take your time. You are doing amazing, and reading challenges have nothing to do with how smart you are! Let's do this step-by-step. ✨"

    @staticmethod
    def dyslexia_format_tool(text_list: List[str]) -> str:
        """Applies clear layout, spacing, and bulleting to reduce visual stress."""
        formatted_output = "\n\n"
        for idx, item in enumerate(text_list, 1):
            formatted_output += f"🔹 STEP {idx}:\n   {item}\n\n"
        return formatted_output


