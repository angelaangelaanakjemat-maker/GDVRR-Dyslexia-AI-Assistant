# 2. AGENTIC ENGINE & DECLARATIVE RULES
# ==========================================
class AgenticDyslexiaAssistant:
    """
    Implements Section 3.0 System Design using Knowledge Engineering
    and the strict GDVRR structural validation process.
    """
    def __init__(self):
        self.tools = DyslexiaSupportTools()
        # Section 3.4: Guardrails banning unverified architectural tags
        self.banned_tokens = [r"Stage \d", r"Phase \d", r"Level \d", r"Intent:", r"Constraint:"]

    def evaluate_declarative_rules(self, user_input: str) -> Dict[str, bool]:
        """
        Implements Section 3.1: IF-THEN Rules Base.
        Evaluates the student's context to match appropriate interventions.
        """
        input_lower = user_input.lower()

        rules_fired = {
            "RULE_1_LONG_TEXT": "lengthy" in input_lower or "long" in input_lower or "paragraphs" in input_lower,
            "RULE_2_DECODING_ISSUE": "decode" in input_lower or "spelling" in input_lower or "sounds" in input_lower,
            "RULE_3_FLUENCY_ISSUE": "slow" in input_lower or "fluency" in input_lower,
            "RULE_4_ANNOYANCE_FRUSTRATION": "confused" in input_lower or "frustrated" in input_lower or "lose attention" in input_lower,
            "RULE_5_WORKING_MEMORY": "remember" in input_lower or "academic" in input_lower or "forget" in input_lower,
            "RULE_8_NEED_INSPIRATION": "how to get better" in input_lower or "give up" in input_lower or "difficult" in input_lower
        }
        return rules_fired

    def execute_agent_loop(self, user_input: str) -> Dict[str, Any]:
        """Runs the internal reasoning trace matching the report specifications."""
        # 1. EVALUATE DECLARATIVE KNOWLEDGE
        rules = self.evaluate_declarative_rules(user_input)

        execution_trace = {
            "matched_rules": [rule for rule, fired in rules.items() if fired],
            "selected_strategies": [],
            "raw_output_steps": []
        }

        # 2. TRIGGER PROCEDURAL INTERVENTIONS
        if rules["RULE_8_NEED_INSPIRATION"] or rules["RULE_4_ANNOYANCE_FRUSTRATION"]:
            execution_trace["selected_strategies"].append("Motivation_Tool")

        if rules["RULE_1_LONG_TEXT"] or rules["RULE_5_WORKING_MEMORY"]:
            execution_trace["selected_strategies"].append("Text_Chunking_Tool")
            execution_trace["selected_strategies"].append("Simplification_Tool")

            # Simulate a sample complex paragraph being broken down for the student
            sample_academic_text = "Dyslexia impacts academic topics because reading long texts overwhelms your working memory capacity."
            simplified_text = self.tools.simplification_tool(sample_academic_text)
            chunks = self.tools.text_chunking_tool(simplified_text)
            execution_trace["raw_output_steps"].extend(chunks)

        if rules["RULE_2_DECODING_ISSUE"]:
            execution_trace["selected_strategies"].append("Phonics_Support_Tool")
            execution_trace["raw_output_steps"].append(self.tools.phonics_support_tool("comprehension"))

        # Baseline default steps if list is empty
        if not execution_trace["raw_output_steps"]:
            execution_trace["raw_output_steps"] = [
                "Read just one short sentence at a time.",
                "Highlight key words using bright colors.",
                "Take a rest after finishing every small part."
            ]

        return execution_trace

    # ==========================================
    # 3. THE GDVRR PROTOCOL AUDIT LAYER
    # ==========================================
    def run_gdvrr_protocol(self, user_input: str) -> Dict[str, Any]:
        """
        Executes Section 4.0: Complete Generate, Deconstruct, Verify, Rewrite, Reflect sequence.
        Performs programmatic self-auditing to capture Epistemic Boundary Violations.
        """
        audit_log = {}

        # --- PHASE 1: GENERATE ---
        # Simulate base generation through the agent reasoning system
        trace = self.execute_agent_loop(user_input)

        # Hallucination Simulation: Intentionally adding the exact error found in section 4.3
        # to demonstrate how the KBS catches and rewrites it programmatically.
        raw_generated_response = (
            "Stage 1 (Intent): Learning Support. Stage 2 (Mood): Perplexed.\n"
            f"{self.tools.motivation_tool()}\n"
            f"Let's work through this text using clean steps:"
            f"{self.tools.dyslexia_format_tool(trace['raw_output_steps'])}"
        )
        audit_log["1. Generate"] = {"raw_output": raw_generated_response}

        # --- PHASE 2: DECONSTRUCT ---
        # Dissecting inputs and tracing matched strategy names
        audit_log["2. Deconstruct"] = {
            "detected_problems": ["Cognitive Overload", "Text Complexity", "Attention Fatigue"],
            "selected_tools": trace["selected_strategies"]
        }

        # --- PHASE 3: VERIFY ---
        # Audit checking against epistemic boundary definitions
        contains_hallucination = False
        for pattern in self.banned_tokens:
            if re.search(pattern, raw_generated_response):
                contains_hallucination = True
                break

        audit_log["3. Verify"] = {
            "compliance_with_expert_rules": True if not contains_hallucination else False,
            "kbs_anomaly_detected": "Violation of Epistemic Boundaries (Knowledge Hallucination)" if contains_hallucination else "None"
        }

        # --- PHASE 4: REWRITE ---
        # Actively executing Section 4.4: Enforcing the strict rewrite rule
        if contains_hallucination:
            # Strip out unverified structural labels via regex clean filters
            cleaned_response = raw_generated_response
            for pattern in self.banned_tokens:
                cleaned_response = re.sub(pattern, "", cleaned_response)
            # Remove clean remnants/double spaces left behind by deletions
            cleaned_response = cleaned_response.replace("\n\n\n", "\n\n").strip()
            # Ensure it strictly preserves core validated tools
            final_response = f"✨ [KBS REWRITE ENGAGED: INTERNAL LABELS REMOVED] ✨\n\n{cleaned_response}"
        else:
            final_response = raw_generated_response

        audit_log["4. Rewrite"] = {"enhanced_output": final_response}

        # --- PHASE 5: REFLECT ---
        # Automated alignment logic processing system validity
        audit_log["5. Reflect"] = {
            "algorithmic_literacy_note": "AI system attempted to introduce unmapped structural tags. "
                                          "The Rewrite layer intervened to force conformance to human expert rules.",
            "status": "System output safely bounded and authenticated."
        }

        return audit_log


